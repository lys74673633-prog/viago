-- 합격 사례 아카이브 (익명화된 벤치마킹용 원문)
create table if not exists public.archive_cases (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  university text not null,
  major text not null,
  admission_year int not null,
  subject text not null,
  title text not null,
  preview text not null,
  full_text text not null,
  performance_text text,
  tags text[] not null default '{}',
  is_published boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists archive_cases_published_idx
  on public.archive_cases (is_published, sort_order desc, admission_year desc);

alter table public.archive_cases enable row level security;

-- 목록/미리보기는 공개, 전문도 select는 허용하되 API에서 권한에 따라 필드를 가림
drop policy if exists "archive_select_published" on public.archive_cases;
create policy "archive_select_published" on public.archive_cases
  for select using (is_published = true);

